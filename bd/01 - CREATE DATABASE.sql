-- CRIANDO O BANCO DE DADOS BD_ACADEMICO VIA SCRIPT --
-- USANDO A FERRAMENTA MySQL Workbench --
CREATE DATABASE BD_ACADEMICO;

-- SELECIONA O BANCO --
USE BD_ACADEMICO;  

-- CRIANDO AS TABELAS --
CREATE TABLE  TURMA (
CO_TURMA			CHAR(11)		NOT NULL,
ANO 				CHAR(4)			NULL,
PERIODO				CHAR(1)			NULL,
DESCRICAO			CHAR(50)		NULL,
DT_INICIAL			DATETIME		NULL,
DT_FINAL			DATETIME		NULL,
NUM_PROVAS			INT				NULL,
CO_CURSO			INT				NULL
);
-- ADICIONANDO CHAVE PRIMARIA DA TABELA TURMA --
ALTER TABLE TURMA ADD CONSTRAINT PK_TURMA
PRIMARY KEY (CO_TURMA);

-- CRIANDO A SEGUNDA TABELA --
CREATE TABLE FREQUENCIA (
CO_ALUNO			INT				NOT NULL,
CO_TURMA			CHAR(11)		NOT NULL,
CO_DISCIPLINA		CHAR(2)			NOT NULL,
DT_FREQUENCIA		DATETIME		NOT NULL,
FREQUENCIA			CHAR(1)			NULL
);
-- ADICIONANDO CHAVES PRIMARIAS DA TABELA FREQUENCIA --
ALTER TABLE FREQUENCIA ADD  CONSTRAINT PK_FREQUENCIA
PRIMARY KEY (CO_ALUNO, CO_TURMA, CO_DISCIPLINA, DT_FREQUENCIA);

-- CRIANDO A TERCEIRA TABELA --
CREATE TABLE ALUNO_TURMA (
CO_ALUNO			INT 			NOT NULL,
CO_TURMA			CHAR(11)		NOT NULL,
DT_MATRICULA		DATETIME		NULL,
DT_CANCELAMENTO		DATETIME		NULL
);
-- ADICIONANDO CHAVES PRIMARIAS DA TEBLA ALUNO_TURMA --
ALTER TABLE ALUNO_TURMA ADD CONSTRAINT PK_ALUNO_TUMA
PRIMARY KEY(CO_ALUNO, CO_TURMA);

-- CRIANDO  A QUARTA TABELA --
CREATE TABLE ALUNO (
CO_ALUNO			INT				NOT NULL,
DT_NASCIMENTO		DATETIME		NULL,
SG_SEXO				CHAR			NULL,
NOME				VARCHAR(20)		NULL,
CO_ESTADOCIVIL		CHAR(1)			NULL,
NO_PAI				VARCHAR(70)		NULL,
NO_MAE				VARCHAR(70)		NULL
);
-- ADICIONANDO CHAVE PRIMARIA DA TABELA ALUNO --
ALTER TABLE ALUNO ADD CONSTRAINT PK_ALUNO
PRIMARY KEY (CO_ALUNO);

-- CRIANDO A QUINTA TABELA --
CREATE TABLE CURSO (
CO_CURSO			INT 			NOT NULL,
NOME				CHAR(40)		NULL
);
-- ADICIONANDO CHAVE PRIMARIA DA TABELA CURSO --
ALTER TABLE CURSO ADD CONSTRAINT PK_CURSO
PRIMARY KEY (CO_CURSO);

-- CRIANDO A SEXTA TABELA --
CREATE TABLE PROFESSOR (
CO_PROFESSOR 		INT				NOT NULL,
SG_SEXO				CHAR(1)			NULL,
NOME				VARCHAR(40)		NULL,
DT_NASCIMENTO		DATETIME		NULL
);
-- ADICIONANDO CHAVE PRIMEARIA DA TABELA PROFESSOR --
ALTER TABLE PROFESSOR ADD CONSTRAINT PK_PROFESSOR
PRIMARY KEY (CO_PROFESSOR);

-- CRIANDO A SÉTIMA TABELA --
CREATE TABLE PROF_TURM_DISC (
CO_PROFESSOR		INT				NOT NULL,
CO_TURMA			CHAR(11)		NOT NULL,
CO_DISCIPLINA		CHAR(2)			NOT NULL
);
-- ADICIONANDO CHAVE ESTRANGEIRA DA TABELA PROF_TURM_DISC --
ALTER TABLE PROF_TURM_DISC ADD CONSTRAINT PK_PROF_TURM_DISC
PRIMARY KEY (CO_PROFESSOR, CO_TURMA, CO_DISCIPLINA);

-- CRIANDO A OITAVA TABELA --
CREATE TABLE DISCIPLINA (
CO_DISCIPLINA		CHAR(2)			NOT NULL,
NO_DISCIPLINA		VARCHAR(30)		NULL
);
-- ADICIONANDO CHAVE PRIMARIA DA TEBELA DISCIPLINA --
ALTER TABLE DISCIPLINA ADD CONSTRAINT PK_DISCIPLINA
PRIMARY KEY (CO_DISCIPLINA);

-- CRIANDO A NONA TABELA --
CREATE TABLE AVALIACAO (
CO_ALUNO			INT 			NOT NULL,
CO_TURMA			CHAR(11)		NOT NULL,
CO_DISCIPLINA		CHAR(2)			NOT NULL,
CO_PROVA			CHAR(3)			NOT NULL,
DT_AVALIACAO		DATETIME		NULL,
NT_AVALIACAO		FLOAT(53)		NULL
);
-- ADICIONANDO CAHVE PRIMARIA DA TABELA AVALIACAO --
ALTER TABLE AVALIACAO ADD CONSTRAINT PK_AVALIACAO
PRIMARY KEY (CO_ALUNO, CO_TURMA, CO_DISCIPLINA, CO_PROVA);

-- CRIANDO A DECIMA TABELA --
CREATE TABLE PROVA (
CO_PROVA			CHAR(3)			NOT NULL,
DS_PROVA			VARCHAR(20)		NULL
);
-- ADICIONANDO CHAVE PRIMARIA DA TABELA PROVA --
ALTER TABLE PROVA ADD CONSTRAINT PK_PROVA
PRIMARY KEY (CO_PROVA);

-- =================================================== --
-- 1. TURMA aponta para CURSO
-- (toda turma pertence a um curso)
-- =================================================== --
ALTER TABLE TURMA ADD CONSTRAINT FK_TURMA_CURSO
FOREIGN KEY (CO_CURSO) REFERENCES CURSO (CO_CURSO);

-- =================================================== --
-- 2. ALUNO_TURMA aponta para ALUNO e para TURMA
-- (ela é a tabela de "matrícula": liga um aluno a uma turma)
-- =================================================== --
ALTER TABLE ALUNO_TURMA ADD CONSTRAINT FK_ALUNOTURMA_ALUNO
FOREIGN KEY (CO_ALUNO) REFERENCES ALUNO (CO_ALUNO);

ALTER TABLE ALUNO_TURMA ADD CONSTRAINT FK_ALUNOTURMA_TURMA
FOREIGN KEY (CO_TURMA) REFERENCES TURMA (CO_TURMA);

-- =================================================== --
-- 3. PROF_TURM_DISC aponta para PROFESSOR, TURMA e DISCIPLINA
-- (ela liga: qual professor dá qual disciplina em qual turma)
-- =================================================== --
ALTER TABLE PROF_TURM_DISC ADD CONSTRAINT FK_PTD_PROFESSOR
FOREIGN KEY (CO_PROFESSOR) REFERENCES PROFESSOR (CO_PROFESSOR);

ALTER TABLE PROF_TURM_DISC ADD CONSTRAINT FK_PTD_TURMA
FOREIGN KEY (CO_TURMA) REFERENCES TURMA (CO_TURMA);

ALTER TABLE PROF_TURM_DISC ADD CONSTRAINT FK_PTD_DISCIPLINA
FOREIGN KEY (CO_DISCIPLINA) REFERENCES DISCIPLINA (CO_DISCIPLINA);

-- =================================================== --
-- 4. FREQUENCIA aponta para ALUNO_TURMA (chave composta!) e DISCIPLINA
-- (só existe frequência se o aluno estiver matriculado na turma)
-- =================================================== --
ALTER TABLE FREQUENCIA ADD CONSTRAINT FK_FREQUENCIA_ALUNOTURMA
FOREIGN KEY (CO_ALUNO, CO_TURMA) REFERENCES ALUNO_TURMA (CO_ALUNO, CO_TURMA);

ALTER TABLE FREQUENCIA ADD CONSTRAINT FK_FREQUENCIA_DISCIPLINA
FOREIGN KEY (CO_DISCIPLINA) REFERENCES DISCIPLINA (CO_DISCIPLINA);

-- =================================================== --
-- 5. AVALIACAO aponta para ALUNO_TURMA (chave composta!), 
--    DISCIPLINA e PROVA
-- (só existe avaliação se o aluno estiver matriculado na turma)
-- =================================================== --
ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_ALUNOTURMA
FOREIGN KEY (CO_ALUNO, CO_TURMA) REFERENCES ALUNO_TURMA (CO_ALUNO, CO_TURMA);

ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_DISCIPLINA
FOREIGN KEY (CO_DISCIPLINA) REFERENCES DISCIPLINA (CO_DISCIPLINA);

ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_PROVA
FOREIGN KEY (CO_PROVA) REFERENCES PROVA (CO_PROVA);

